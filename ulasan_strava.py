# Mengambil data thumbsUpCount
data = df_feature['thumbsUpCount']

# Menghitung kuartil
Q1 = data.quantile(0.25)
Q3 = data.quantile(0.75)

# Menghitung IQR
IQR = Q3 - Q1

# Menentukan batas pencilan
batas_bawah = Q1 - (1.5 * IQR)
batas_atas = Q3 + (1.5 * IQR)

# Mengidentifikasi outlier
outlier = df_feature[
    (df_feature['thumbsUpCount'] < batas_bawah) |
    (df_feature['thumbsUpCount'] > batas_atas)
]

# Menampilkan hasil
print("Q1:", Q1)
print("Q3:", Q3)
print("IQR:", IQR)
print("Batas bawah:", batas_bawah)
print("Batas atas:", batas_atas)

