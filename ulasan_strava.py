from google_play_scraper import reviews, Sort
from datetime import datetime, timedelta, timezone
import time

APP_ID = 'com.strava'
LANGUAGE = 'id'
COUNTRY = 'id'

END_DATE = datetime(2026, 11, 20, 23, 59, 59, tzinfo=timezone.utc)
START_DATE = END_DATE - timedelta(days=365)

all_reviews = []
continuation_token = None
page = 1

while True:

    print(f"Scraping halaman {page}...")

    result, continuation_token = reviews(
        APP_ID,
        lang=LANGUAGE,
        country=COUNTRY,
        sort=Sort.NEWEST,
        count=200,
        continuation_token=continuation_token
    )

    if not result:
        break

    all_reviews.extend(result)

    oldest_review = min(review['at'] for review in result)

    print("Total review terkumpul:", len(all_reviews))
    print("Review tertua batch:", oldest_review)

    if oldest_review.replace(tzinfo=timezone.utc) < START_DATE:
        print("Batas periode penelitian tercapai.")
        break

    if continuation_token is None:
        break

    page += 1
    time.sleep(0.5)

print("Scraping selesai.")
print("Total data hasil scraping:", len(all_reviews))

